static rt_dac_device_t dac_dev;     // DAC设备句柄
static uint16_t dac_buffer_ch1[BUFFER_SIZE]; // 通道1数据
static uint16_t dac_buffer_ch2[BUFFER_SIZE]; // 通道2数据

// 初始化双通道缓冲区（示例：通道1正弦波，通道2三角波）
static void init_dac_buffers(void)
{
    for (int i = 0; i < BUFFER_SIZE; i++) {
        dac_buffer_ch1[i] = 512;
        dac_buffer_ch2[i] = 512;
    }
}

int dac_dma_init(void)
{
    // 1. 查找DAC设备（只有dac1）
    dac_dev = (rt_dac_device_t)rt_device_find(DAC_DEV_NAME);
    if (!dac_dev) {
        rt_kprintf("[ERROR] DAC device not found!\n");
        return RT_ERROR;
    }

    // 2. 初始化缓冲区
    init_dac_buffers();

    // 3. 启用双通道
    rt_dac_enable(dac_dev, 1);  // 通道1
    rt_dac_enable(dac_dev, 2);  // 通道2
//
    // 4. 启动DMA传输
    HAL_DAC_Start_DMA(&hdac, DAC_CHANNEL_1, (uint32_t *)user_dac_wave_1khz_buf, DAC_WAVE_1KHZ_BUF_SIZE, DAC_ALIGN_12B_R);
    HAL_DAC_Start_DMA(&hdac, DAC_CHANNEL_2, (uint32_t *)dac_buffer_ch2, BUFFER_SIZE, DAC_ALIGN_12B_R);
//
    // 5. 启动TIM2触发
    HAL_TIM_Base_Start(&htim2);

    rt_kprintf("DAC dual-channel DMA output started!\n");
    return RT_EOK;
}

void User_Dac_Dma_Start(void)
{
    HAL_DAC_Start_DMA(&hdac, DAC_CHANNEL_1,(uint32_t *)user_dac.set_wave_buf,user_dac.set_wave_size,DAC_ALIGN_12B_R);
    HAL_TIM_Base_Start(&htim2);
    HAL_DAC_Start(&hdac, DAC_CHANNEL_1);
}

void User_Dac_Dma_Stop(void)
{
    //HAL_DAC_Stop_DMA(&hdac, DAC_CHANNEL_1);
    HAL_TIM_Base_Stop(&htim2);
    HAL_DAC_SetValue(&hdac, DAC_CHANNEL_1,DAC_ALIGN_12B_R,4096/2);
}
/*​
 * @brief 转换DAC数据从0-2.5V到0.1-2.4V
 *
 * @param original 原始DAC值 (0-4095)
 * @return uint16_t 转换后的DAC值 (124-3631)
 */
static uint16_t convert_dac_value_range(uint16_t original)
{
    if (original > 4095)
        original = 4095; // 限制最大值

    // 转换公式: new_value = (3631-124)) / 4095) + 124
    // 使用整数运算避免浮点运算
    return ((original * (3631-124)) / 4095) + 124;
}
void User_Dac_Set_Fre(FRE_t Fre)
{
    if(user_dac.is_init)
    {
        HAL_TIM_Base_Stop(&htim2);
    }
    else {
        user_dac.is_init = 1;
    }
    switch(Fre)
    {
        //频率设定的具体值与 user_dac_wave_buf 大小有关系
        case DAC_WORK_FRE_100Hz:
            //定时器时钟频率是72M，168000000/84/100/200=100
            htim2.Init.Prescaler = 42-1;
            htim2.Init.Period = 100-1;
            user_dac.set_wave_buf = user_dac_wave_100hz_buf;
            user_dac.set_wave_size = sizeof(user_dac_wave_100hz_buf)/sizeof(user_dac_wave_100hz_buf[0]);
            user_dac.set_fre = DAC_WORK_FRE_100Hz;
            break;
        case DAC_WORK_FRE_1kHz:
            //定时器时钟频率是72M，84000000/84/10/100=1k
            htim2.Init.Prescaler = 84-1;
            htim2.Init.Period = 10-1;
            user_dac.set_wave_buf = user_dac_wave_1khz_buf;
            user_dac.set_wave_size = sizeof(user_dac_wave_1khz_buf)/sizeof(user_dac_wave_1khz_buf[0]);
            user_dac.set_fre = DAC_WORK_FRE_1kHz;
            break;

        case DAC_WORK_FRE_10kHz:
            //定时器时钟频率是72M，168000000/168/20/50=10k
            htim2.Init.Prescaler = 84-1;
            htim2.Init.Period = 20-1;
            user_dac.set_wave_buf = user_dac_wave_10khz_buf;
            user_dac.set_wave_size = sizeof(user_dac_wave_10khz_buf)/sizeof(user_dac_wave_10khz_buf[0]);
            user_dac.set_fre = DAC_WORK_FRE_10kHz;
            break;
        default:
            htim2.Init.Prescaler = 84-1;
            htim2.Init.Period = 10-1;
            user_dac.set_wave_buf = user_dac_wave_1khz_buf;
            user_dac.set_wave_size = sizeof(user_dac_wave_1khz_buf)/sizeof(user_dac_wave_1khz_buf[0]);
            user_dac.set_fre = DAC_WORK_FRE_1kHz;
            break;
    }
    htim2.Instance = TIM2;
    htim2.Init.CounterMode = TIM_COUNTERMODE_UP;
    htim2.Init.ClockDivision = TIM_CLOCKDIVISION_DIV1;
    htim2.Init.AutoReloadPreload = TIM_AUTORELOAD_PRELOAD_ENABLE;
    if (HAL_TIM_Base_Init(&htim2) != HAL_OK)
    {
        Error_Handler();
    }

}
